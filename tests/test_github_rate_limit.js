'use strict';
const assert=require('node:assert/strict');
const {rateLimitError,githubResponseError,promptRateLimit,parseCLIResponse}=require('../efs/github/github_rate_limit');
const {executeResolution}=require('../efs/merge/merge_resolution');
const {createMergeBatch}=require('../efs/merge/merge_batch');
(async()=>{
 const now=Date.now();
 const {rateLimitMessage}=require('../efs/github/github_rate_limit');
 assert.match(rateLimitMessage(now+121000,'relative',now), /3m/);
 assert.match(rateLimitMessage(now+45000,'relative',now), /45s/);
 assert.match(rateLimitMessage(now-1,'relative',now), /Ready to retry/);
 assert.equal(rateLimitError({status:403,message:'Resource not accessible by integration'},now),null,'Permission errors are not rate limits');
 const headers={'x-ratelimit-remaining':'0','x-ratelimit-reset':String(Math.floor(now/1000)+90)};
 const limited=rateLimitError({status:403,headers},now);
 assert(limited.rateLimited);assert.equal(limited.code,'GITHUB_RATE_LIMIT');assert(limited.retryAt>=now+89000);
 const secondary=rateLimitError({status:429,headers:{'retry-after':'120'}},now);
 assert.equal(secondary.retryAt,now+121000);
 assert.equal(rateLimitError({status:403,message:'You have exceeded a secondary rate limit.'},now).retryAt,now+60000);
 const responseError=await githubResponseError({status:403,headers:new Headers(headers),json:async()=>({message:'API rate limit exceeded'})},'fallback');
 assert(responseError.rateLimited);
 const parsed=parseCLIResponse('HTTP/2.0 403 Forbidden\r\nx-ratelimit-remaining: 0\r\nx-ratelimit-reset: '+headers['x-ratelimit-reset']+'\r\n\r\n{"message":"API rate limit exceeded"}');
 assert.equal(parsed.status,403);assert.equal(JSON.parse(parsed.body).message,'API rate limit exceeded');
 assert(rateLimitError({...parsed,message:'API rate limit exceeded'},now).rateLimited);
 let notices=0,retries=0,delay,callback;
 const vscode={window:{showWarningMessage:async(message,action)=>{notices++;assert(message.includes('paused'));return action;}}};
 await promptRateLimit(vscode,limited,{retry:()=>{retries++;},schedule:(fn,ms)=>{callback=fn;delay=ms;return {unref(){}};}});
 assert(delay>0);assert.equal(retries,0,'Never retry immediately');
 await promptRateLimit(vscode,limited);assert.equal(notices,1,'No prompt storm for the same cooldown');
 callback();await new Promise(resolve=>setImmediate(resolve));assert.equal(retries,1);
 let accept, queued, statusRetries=0, batchRetries=0;
 const pendingHost={window:{showWarningMessage:()=>new Promise(resolve=>{accept=resolve;})}};
 const pendingNotice=promptRateLimit(pendingHost,limited,{retry:()=>statusRetries++,schedule:fn=>{queued=fn;}});
 await promptRateLimit(pendingHost,limited,{retryPriority:1,retry:()=>batchRetries++});
 accept('Retry after reset');await pendingNotice;queued();await new Promise(resolve=>setImmediate(resolve));
 assert.equal(batchRetries,1,'A paused merge batch takes priority over status-only refresh in the shared retry prompt');
 assert.equal(statusRetries,0);
 const selection={repository:'o/r',pullRequests:[{number:1,title:'Feature',url:'https://github.com/o/r/pull/1',head:'feature',headSha:'a'.repeat(40),base:'main'}]};
 const states=[];
 const batch=await createMergeBatch(selection,{api:async()=>{throw limited;},destination:'https://chatgpt.com/',onState:async state=>states.push(state)});
 assert.equal(batch.url,undefined);assert.equal(states.at(-1).rateLimit.retryAt,limited.retryAt);
 assert.equal(states.at(-1).deferred.length,0,'Rate limits are not human conflict decisions');batch.dispose();
 const result=await executeResolution({version:1,repository:'o/r',results:[{number:1,headSha:'a'.repeat(40),baseSha:'b'.repeat(40),patch:null,explanation:'Keep the feature.'}]},selection,{merge:async()=>{throw limited;}});
 assert.equal(result.results[0].status,'waiting');assert.equal(result.results[0].retryAt,limited.retryAt);
 console.log('GitHub primary/secondary limits, permission errors, delayed retry prompts and batch pause checks passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
