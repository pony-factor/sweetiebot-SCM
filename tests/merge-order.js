'use strict';
const assert = require('node:assert/strict');
const { orderMergeCandidates } = require('../extension/merge/order');
const pr = (number, extra = {}) => ({ number, head: 'feature-' + number, base: 'main', ...extra });
const numbers = prs => orderMergeCandidates(prs).map(pr => pr.number);
assert.deepEqual(numbers([pr(1, {mergeable:false}), pr(2), pr(3, {mergeable:true})]), [3, 2, 1]);
assert.deepEqual(numbers([pr(1, {mergeable:true, mergeableState:'unstable'}), pr(2, {mergeable:true})]), [2, 1]);
assert.deepEqual(numbers([pr(1, {mergeable:false, attempts:1}), pr(2, {mergeable:false})]), [2, 1], 'A stalled conflict does not monopolize review');
assert.deepEqual(numbers([pr(2, {mergeable:true, base:'feature-1'}), pr(1, {mergeable:false})]), [1, 2], 'Readiness never bypasses selected stack ancestry');
assert.deepEqual(numbers([pr(1), pr(2), pr(3, {base:'feature-2'})]), [2, 1, 3], 'An equally ready ancestor unlocks its child');
assert.deepEqual(numbers([pr(1, {changeSize:500}), pr(2, {changeSize:5})]), [2, 1]);
assert.deepEqual(numbers([pr(8), pr(5), pr(2)]), [8, 5, 2], 'Lane direction remains a deterministic tie-break');
assert.deepEqual(numbers([pr(1, {waitingFor:[9], mergeable:true}), pr(2, {mergeable:false})]), [2, 1], 'A deferred ancestor still blocks its child');
console.log('Readiness, stack dependency, progress, integration size and lane tie-break checks passed.');
